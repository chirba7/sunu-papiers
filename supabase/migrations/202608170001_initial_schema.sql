create or replace view public.admin_dashboard with (security_invoker = true) as
select
  (select count(*) from public.profiles where role = 'citizen' and active) as citizens,
  (select count(*) from public.profiles where role = 'delegate' and active) as delegates,
  (select count(*) from public.houses where active) as houses,
  (select count(*) from public.document_requests) as requests,
  (select count(*) from public.document_requests where status = 'pending') as pending;

grant select on public.admin_dashboard to authenticated;

