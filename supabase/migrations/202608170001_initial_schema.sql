create or replace function public.handle_new_auth_user()
returns trigger language plpgsql security definer set search_path = '' as $$
declare
  assigned_role public.user_role;
begin
  assigned_role := case
    when new.raw_app_meta_data ->> 'role' in ('admin', 'delegate')
      then (new.raw_app_meta_data ->> 'role')::public.user_role
    else 'citizen'::public.user_role
  end;

  insert into public.profiles(id, role, first_name, last_name, phone)
  values (
    new.id,
    assigned_role,
    coalesce(new.raw_user_meta_data ->> 'first_name', ''),
    coalesce(new.raw_user_meta_data ->> 'last_name', ''),
    nullif(regexp_replace(coalesce(new.phone, new.raw_user_meta_data ->> 'phone', ''), '\D', '', 'g'), '')
  );

  if assigned_role = 'citizen' then
    insert into public.citizen_profiles(user_id) values (new.id);
  end if;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created after insert on auth.users
for each row execute function public.handle_new_auth_user();

create or replace function public.prepare_document_request()
returns trigger language plpgsql security definer set search_path = '' as $$
declare selected_house public.houses%rowtype;
begin
  select * into selected_house from public.houses where id = new.house_id and active;
  if not found then raise exception 'Maison introuvable ou archivee'; end if;
  if selected_house.delegate_id is null then raise exception 'Aucun delegue affecte a cette maison'; end if;
  new.delegate_id := selected_house.delegate_id;
  new.reference := 'CD-' || extract(year from now() at time zone 'Africa/Dakar')::integer || '-' || lpad(new.id::text, 4, '0');
  return new;
end;
$$;

drop trigger if exists document_request_prepare on public.document_requests;
create trigger document_request_prepare before insert on public.document_requests
for each row execute function public.prepare_document_request();

create or replace function public.current_user_role()
returns public.user_role language sql stable security definer set search_path = '' as $$
  select role from public.profiles where id = (select auth.uid()) and active;
$$;

create or replace function public.protect_profile_security_fields()
returns trigger language plpgsql set search_path = '' as $$
begin
  if (old.role, old.active) is distinct from (new.role, new.active)
     and current_user not in ('postgres', 'service_role', 'supabase_admin')
     and coalesce(public.current_user_role(), 'citizen'::public.user_role) <> 'admin' then
    raise exception 'Seul un administrateur peut modifier le role ou le statut';
  end if;
  return new;
end;
$$;

drop trigger if exists profiles_protect_security_fields on public.profiles;
create trigger profiles_protect_security_fields before update on public.profiles
for each row execute function public.protect_profile_security_fields();

