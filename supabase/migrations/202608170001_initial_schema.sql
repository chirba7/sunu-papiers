drop policy if exists profiles_select on public.profiles;
create policy profiles_select on public.profiles for select to authenticated using (
  id = (select auth.uid()) or public.current_user_role() = 'admin' or
  (public.current_user_role() = 'delegate' and exists (
    select 1 from public.document_requests r where r.citizen_id = profiles.id and r.delegate_id = (select auth.uid())
  ))
);
drop policy if exists profiles_update on public.profiles;
create policy profiles_update on public.profiles for update to authenticated
using (id = (select auth.uid()) or public.current_user_role() = 'admin')
with check (id = (select auth.uid()) or public.current_user_role() = 'admin');

drop policy if exists citizen_profiles_select on public.citizen_profiles;
create policy citizen_profiles_select on public.citizen_profiles for select to authenticated using (
  user_id = (select auth.uid()) or public.current_user_role() = 'admin' or
  (public.current_user_role() = 'delegate' and exists (
    select 1 from public.document_requests r where r.citizen_id = citizen_profiles.user_id and r.delegate_id = (select auth.uid())
  ))
);
drop policy if exists citizen_profiles_update on public.citizen_profiles;
create policy citizen_profiles_update on public.citizen_profiles for update to authenticated
using (user_id = (select auth.uid()) or public.current_user_role() = 'admin')
with check (user_id = (select auth.uid()) or public.current_user_role() = 'admin');

drop policy if exists houses_select on public.houses;
create policy houses_select on public.houses for select to authenticated using (
  active or public.current_user_role() = 'admin' or exists (
    select 1 from public.document_requests r where r.house_id = houses.id and (r.citizen_id = (select auth.uid()) or r.delegate_id = (select auth.uid()))
  )
);
drop policy if exists houses_admin_insert on public.houses;
create policy houses_admin_insert on public.houses for insert to authenticated with check (public.current_user_role() = 'admin');
drop policy if exists houses_admin_update on public.houses;
create policy houses_admin_update on public.houses for update to authenticated
using (public.current_user_role() = 'admin') with check (public.current_user_role() = 'admin');

drop policy if exists requests_select on public.document_requests;
create policy requests_select on public.document_requests for select to authenticated using (
  citizen_id = (select auth.uid()) or delegate_id = (select auth.uid()) or public.current_user_role() = 'admin'
);
drop policy if exists requests_citizen_insert on public.document_requests;
create policy requests_citizen_insert on public.document_requests for insert to authenticated with check (
  citizen_id = (select auth.uid()) and public.current_user_role() = 'citizen'
);
drop policy if exists requests_delegate_update on public.document_requests;
create policy requests_delegate_update on public.document_requests for update to authenticated
using (delegate_id = (select auth.uid()) or public.current_user_role() = 'admin')
with check (delegate_id = (select auth.uid()) or public.current_user_role() = 'admin');

