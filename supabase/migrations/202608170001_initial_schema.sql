do $$ begin
  create type public.user_role as enum ('admin', 'delegate', 'citizen');
exception when duplicate_object then null; end $$;

do $$ begin
  create type public.request_status as enum ('pending', 'processing', 'approved', 'rejected');
exception when duplicate_object then null; end $$;

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  role public.user_role not null default 'citizen',
  first_name text not null default '',
  last_name text not null default '',
  phone text unique,
  active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint profiles_phone_format check (phone is null or phone ~ '^[0-9]{9}$')
);

create table if not exists public.citizen_profiles (
  user_id uuid primary key references public.profiles(id) on delete cascade,
  father_first_name text not null default '',
  father_last_name text not null default '',
  mother_first_name text not null default '',
  mother_last_name text not null default '',
  birth_date date,
  birth_place text not null default '',
  identity_number text not null default '',
  villa_number text not null default '',
  id_front_path text,
  id_back_path text,
  quartier text not null default '',
  resident_since_year integer,
  updated_at timestamptz not null default now(),
  constraint citizen_resident_year check (resident_since_year is null or resident_since_year between 1900 and 2100)
);

create table if not exists public.houses (
  id bigint generated by default as identity primary key,
  region text not null,
  departement text not null,
  commune text not null,
  quartier text not null,
  delegate_id uuid references public.profiles(id) on delete set null,
  certificate_path text not null,
  active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint houses_region_upper check (region = upper(region)),
  constraint houses_departement_upper check (departement = upper(departement)),
  constraint houses_commune_upper check (commune = upper(commune)),
  constraint houses_quartier_upper check (quartier = upper(quartier))
);

create unique index if not exists houses_active_quartier_unique
  on public.houses (upper(quartier)) where active;
create unique index if not exists houses_active_delegate_unique
  on public.houses (delegate_id) where active and delegate_id is not null;

create table if not exists public.document_requests (
  id bigint generated by default as identity primary key,
  reference text unique,
  citizen_id uuid not null references public.profiles(id) on delete restrict,
  house_id bigint not null references public.houses(id) on delete restrict,
  delegate_id uuid references public.profiles(id) on delete set null,
  document_type text not null default 'Certificat de domicile',
  status public.request_status not null default 'pending',
  address text not null,
  birth_date date,
  birth_place text not null default '',
  identity_number text not null default '',
  lot_number text not null default '',
  certificate_path text,
  submitted_at timestamptz not null default now(),
  processed_at timestamptz,
  updated_at timestamptz not null default now()
);

create index if not exists document_requests_citizen_idx on public.document_requests(citizen_id, submitted_at desc);
create index if not exists document_requests_delegate_idx on public.document_requests(delegate_id, status, submitted_at desc);
create index if not exists document_requests_house_idx on public.document_requests(house_id);

